"""Generate the dummy bank's 100 synthetic customers (deterministic, standard library only).

    python bank/core-db/generate_customers.py      # writes bank/core-db/init/20_customers.sql

No real person: names are drawn from short lists, everything else from a fixed random seed.
Edge cases are planted on purpose so every eligibility rule and data check is exercised:

    DB0001-DB0003  under 18                     -> decline (minimum age)
    DB0004-DB0007  an account written off       -> decline (write-off)
    DB0008-DB0010  bankruptcy on file           -> decline (bankruptcy)
    DB0011-DB0015  two or more accounts in arrears -> refer
    DB0016-DB0018  no bureau score              -> refer (missing data)
    DB0019-DB0020  bureau report two years old  -> refer if the strategy limits data age
    DB0021-DB0100  ordinary customers with a spread of scores, incomes and debts
"""

from __future__ import annotations

import random
from datetime import date, timedelta
from pathlib import Path

TODAY = date(2026, 10, 27)
FIRST = ["Maria", "Nikos", "Eleni", "Giorgos", "Anna", "Kostas", "Sofia", "Dimitris", "Katerina",
         "Yannis", "Ioanna", "Petros", "Christina", "Alexandros", "Despina", "Stavros"]
LAST = ["Papadopoulou", "Georgiou", "Nikolaou", "Ioannou", "Konstantinou", "Vasileiou",
        "Christodoulou", "Antoniou", "Pappas", "Oikonomou", "Makri", "Dimitriou"]
EMPLOYMENT = ["SALARIED"] * 6 + ["SELF_EMPLOYED"] * 2 + ["PENSIONER"]


def q(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main() -> None:
    rnd = random.Random(20261027)
    customers, bureau, accounts, records, exposure = [], [], [], [], []
    for n in range(1, 101):
        cid = f"DB{n:04d}"
        age = rnd.randint(16, 17) if n <= 3 else rnd.randint(21, 72)
        dob = TODAY - timedelta(days=age * 365 + rnd.randint(10, 300))
        employment = "PENSIONER" if age >= 67 else rnd.choice(EMPLOYMENT)
        income = round(rnd.uniform(900, 5200), 2)
        customers.append((cid, rnd.choice(FIRST), rnd.choice(LAST), dob.isoformat(), employment,
                          income))

        score = None if 16 <= n <= 18 else max(300, min(900, int(rnd.gauss(680, 70))))
        as_of = TODAY - timedelta(days=730 if n in (19, 20) else rnd.randint(1, 20))
        bureau.append((cid, score, as_of.isoformat()))

        statuses = ["CURRENT"] * rnd.randint(1, 4)
        if 4 <= n <= 7:
            statuses.append("WRITTEN_OFF")
        if 11 <= n <= 15:
            statuses += ["ARREARS_30", "ARREARS_60"]
        elif rnd.random() < 0.08:
            statuses.append("ARREARS_30")  # one arrears account: no referral on its own
        monthly_debt = 0.0
        for i, status in enumerate(statuses, 1):
            balance = round(rnd.uniform(300, 12000), 2)
            payment = round(balance / rnd.choice([36, 60, 120]), 2)
            monthly_debt += payment if status != "WRITTEN_OFF" else 0
            accounts.append((f"{cid}-A{i}", cid, rnd.choice(["CARD", "LOAN", "OVERDRAFT"]),
                             status, balance, payment))
        records.append((cid, 8 <= n <= 10))

        total = round(sum(a[4] for a in accounts if a[1] == cid), 2)
        for days_ago in (30, 1):  # two snapshots: the engine must read the latest
            exposure.append((cid, (TODAY - timedelta(days=days_ago)).isoformat(),
                             round(total * (0.97 if days_ago == 30 else 1.0), 2)))
        customers[-1] = (*customers[-1], round(monthly_debt, 2))

    out = ["-- GENERATED by generate_customers.py: 100 synthetic customers, no real person.",
           "BEGIN;"]
    out += [f"INSERT INTO core.customers VALUES ({', '.join(q(v) for v in c)});"
            for c in customers]
    out += [f"INSERT INTO core.bureau_reports VALUES ({', '.join(q(v) for v in b)});"
            for b in bureau]
    out += [f"INSERT INTO core.accounts VALUES ({', '.join(q(v) for v in a)});" for a in accounts]
    out += [f"INSERT INTO core.public_records VALUES ({q(c)}, {q(f)});" for c, f in records]
    out += [f"INSERT INTO risk.customer_exposure_daily VALUES ({', '.join(q(v) for v in e)});"
            for e in exposure]
    out.append("COMMIT;")
    target = Path(__file__).with_name("init") / "20_customers.sql"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target} ({len(customers)} customers, {len(accounts)} accounts)")


if __name__ == "__main__":
    main()
